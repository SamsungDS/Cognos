/**
 * @brief Enable SLA tracking on the devices where the application is already
 * running This API works only for one node at a time.
 * @param node_names List of nodes (only one node expected)
 * @param command_params_str JSON string containing the command parameters
 * {
    "app_desired_qos": {
      "avg_latency": 2500
    },
    "app_name": "gemfire",
    "app_pid": 987654321,
    "app_total_data_set_MB": 4096,
    "devices": [
      {
        "device_allocated_capacity_mb": 4096,
        "device_id": "localhost_2"
      }
    ],
    "hot_data_size_MB": 2048
  }
 * @param[out] output JSON string containing the output
 * @return Status  GRPC status
 */
Status ControllerServicer::SetAppSLACommand(
    const std::string &cluster_name, const std::string &node_name,
    const std::string &command_params_str, std::string &output) {
  json command_params;
  std::string logger_str;
  DeviceInfo dev;
  std::vector<DeviceInfo> user_devices;
  Status cmd_status;
  int status = -1;

  uint64_t sla_latency_ns = 0;
  std::string app_name;
  std::string logic_module;
  uint64_t app_allocated_capacity;
  uint64_t app_hotdata_size;
  pid_t app_pid;
  node_info node_details;

  if (node_name.empty()) {
    logger_str = "Empty node name provided";
    svk_logger(CONTROLLER_LOGGER_MODULE_NAME, level_E::ERROR,
               logger_str.c_str());
    return Status(grpc::INVALID_ARGUMENT, logger_str);
  }

  if (command_params_str.empty()) {
    logger_str =
        "SetAppSLACommand called with empty cluster/node name or command_name "
        "or command_params";
    svk_logger(CONTROLLER_LOGGER_MODULE_NAME, level_E::ERROR,
               logger_str.c_str());
    return Status(grpc::INVALID_ARGUMENT, logger_str);
  }

  status = GetNodeInfo(node_name, node_details);
  if (status != 0) {
    logger_str = "Invalid node name given - " + node_name;
    svk_logger(CONTROLLER_LOGGER_MODULE_NAME, level_E::ERROR,
               logger_str.c_str());
    return Status(grpc::UNKNOWN, logger_str);
  }

  try {
    command_params = json::parse(command_params_str);
    // Extracting the required fields
    app_name = command_params.at("app_name").get<std::string>();
    app_pid = command_params.at("app_pid").get<pid_t>();
    app_allocated_capacity = command_params.value("app_total_data_set_MB", -1);
    app_hotdata_size = command_params.value("hot_data_size_MB", -1);
    logic_module = command_params.value("logic_module", "mlc");
    sla_latency_ns =
        command_params["app_desired_qos"]["avg_latency_ns"].get<uint64_t>();

    // Extracting the array of devices
    json devices_array = command_params.value("devices", json::array());
    if (!devices_array.is_array()) {
      logger_str = "Device array is not provided in JSON input";
      svk_logger(CONTROLLER_LOGGER_MODULE_NAME, level_E::ERROR,
                 logger_str.c_str());
      return Status(grpc::UNKNOWN, logger_str);
    }
    if (devices_array.empty()) {
      logger_str = "Device array is empty";
      svk_logger(CONTROLLER_LOGGER_MODULE_NAME, level_E::ERROR,
                 logger_str.c_str());
      return Status(grpc::UNKNOWN, logger_str);
    }

    // Validate the devices checking for the following
    // - device belongs to the node given in the input
    // - device id is valid
    // - device is not marked faulty
    // - allocated memory is more than the available
    for (const auto &device : devices_array) {
      DeviceInfo tmp_device_info;
      std::string device_numa = device.at("device_numa").get<std::string>();
      dev.controller_generated_id =
          generate_unique_device_id(node_details.node_ip, device_numa);
      status = g_sla_device_hlpr->GetDeviceInfo(dev.controller_generated_id,
                                                tmp_device_info);
      if (status != 0) {
        logger_str =
            "Invalid device id provided - " + dev.controller_generated_id;
        svk_logger(CONTROLLER_LOGGER_MODULE_NAME, level_E::ERROR,
                   logger_str.c_str());
        return Status(grpc::UNKNOWN, logger_str);
      }
      if (tmp_device_info.internal_status != Device_Status_E::DEVICE_ONLINE) {
        logger_str = "Device id provided - " + dev.controller_generated_id +
                     " is invalid/faulty/offline";
        svk_logger(CONTROLLER_LOGGER_MODULE_NAME, level_E::ERROR,
                   logger_str.c_str());
        return Status(grpc::UNKNOWN, logger_str);
      }
      dev.allocated_capacity_mb =
          device.value("device_allocated_capacity_mb",
                       tmp_device_info.available_capacity_mb);

      if (dev.allocated_capacity_mb > tmp_device_info.available_capacity_mb) {
        logger_str = "Device id provided - " + dev.controller_generated_id +
                     " is allocated more than the available capacity";
        svk_logger(CONTROLLER_LOGGER_MODULE_NAME, level_E::ERROR,
                   logger_str.c_str());
        return Status(grpc::UNKNOWN, logger_str);
      }
      dev.device_qos.avg_latency_ns = tmp_device_info.device_qos.avg_latency_ns;
      dev.numa = tmp_device_info.numa;
      dev.node_name = tmp_device_info.node_name;
      dev.device_type = tmp_device_info.device_type;
      user_devices.push_back(dev);
    }

  } catch (const json::exception &e) {
    logger_str = "Exception in parsing the arguments" + std::string(e.what());
    svk_logger(CONTROLLER_LOGGER_MODULE_NAME, level_E::ERROR,
               logger_str.c_str());
    return Status(grpc::UNKNOWN, logger_str);
  }

  // Check the device's node_name and send the SLA Tracking requests to that
  // node
  json device_array_json = json::array();
  json device;

  for (auto dev : user_devices) {
    logger_str = "Device with node_name: " + dev.node_name +
                 " and passed node info: " + node_details.node_ip;
    svk_logger(CONTROLLER_LOGGER_MODULE_NAME, level_E::TRACE,
               logger_str.c_str());
    if (dev.node_name == node_details.node_ip) {
      device["device_numa"] = std::to_string(dev.numa);
      device["device_sla_latency_ns"] = dev.device_qos.avg_latency_ns;
      device["device_id"] = dev.controller_generated_id;
      device_array_json.push_back(device);
    }
  }

  g_sla_device_hlpr->UpdateDeviceAllocatedCapacity(user_devices);
  cmd_status = EnableSLATracking(node_details.node_ip, node_details.node_port,
                                 device_array_json, app_name, app_pid,
                                 sla_latency_ns, logic_module);
  if (!cmd_status.ok()) {
    return cmd_status;
  }

  App_Info app_info;

  app_info.app_name = app_name;
  app_info.node_ip = node_details.node_ip;
  app_info.appLatencyns = sla_latency_ns;
  app_info.size = app_allocated_capacity;
  app_info.pid = app_pid;
  app_info.app_hotdata_size = app_hotdata_size;
  for (const auto &dev : user_devices) {
    AppDeviceInfo app_device;
    app_device.controller_generated_id = dev.controller_generated_id;
    app_device.allocated_capacity_mb = dev.allocated_capacity_mb;
    app_device.used_for_tiering = false;
    app_info.app_device_map[dev.numa] = app_device;
  }

  for (const auto &dev : user_devices) {
    g_sla_device_hlpr->SetAppInfo(dev.controller_generated_id, app_info);
  }

  json output_json;
  json sla_json;
  sla_json["avg_latency_ns"] = sla_latency_ns;

  output_json["cluster_name"] = cluster_name;
  output_json["node_name"] = node_name;
  output_json["app_name"] = app_name;
  output_json["app_pid"] = app_pid;
  output_json["slat_enabled"] = true;
  output_json["sla"] = sla_json;

  output = output_json.dump();

  logger_str = "SetAppSLACommand processed successfully";
  svk_logger(CONTROLLER_LOGGER_MODULE_NAME, level_E::INFO, logger_str.c_str());
  return Status::OK;
}

Status ControllerServicer::SLAManagementAPI(
    ServerContext *ctxt, const svk::SLAManagementRequest *req,
    svk::SLAManagementResponse *resp) {
  std::string logger_str;
  Status status;
  std::vector<std::string> node_names;
  std::string output;

  std::string cluster_name = req->cluster_name();
  std::string node_name = req->node_name();
  std::string app_name = req->app_name();
  std::string command_name = req->command_name();
  std::string command_params_str = req->command_params();

  if ((cluster_name.empty() && node_name.empty()) || command_name.empty()) {
    logger_str =
        "SLAManagementAPI called with empty cluster/node name or command_name "
        "or command_params";
    svk_logger(CONTROLLER_LOGGER_MODULE_NAME, level_E::ERROR,
               logger_str.c_str());
    return Status(grpc::INVALID_ARGUMENT, logger_str);
  }

  // Get the node names of the given cluster so that the devices of those
  // nodes alone are acquired
  if (node_name.length()) {
    node_names.push_back(node_name);
  } else {
    for (auto itr = m_cluster_map[cluster_name].begin();
         itr != m_cluster_map[cluster_name].end(); ++itr) {
      node_names.push_back(itr->first);
    }
  }

  if (command_name == "get_devices_with_sla_info") {
    status = GetDevicesWithSLAInfo(node_names, output);
  } else if (command_name == "set_app_sla") {
    status =
        SetAppSLACommand(cluster_name, node_name, command_params_str, output);
  } else {
    status = Status(grpc::UNKNOWN, "Invalid command_name passed");
  }

  if (status.ok()) {
    resp->set_api_version(API_VERSION);
    resp->set_response(output);
    resp->set_error_code(SVK_STATUS_SUCCESS);
  }

  return status;
}

int ControllerServicer::HlprGetNodeDetails(std::string const &node_name,
                                           std::string &node_port,
                                           std::string &cluster_name,
                                           std::string &node_ip) {
  int status = -1;
  std::string logger_str;

  if (node_name.length()) {
    try {
      // Note: must use the node_name to find the ip/cluster, not the IP
      node_info n = m_registered_nodes.at(node_name);
      cluster_name = n.cluster_name;
      // Send the node_ip to ProcessControllerCommand for now
      node_ip = n.node_ip;
      node_port = n.node_port;
    } catch (const std::out_of_range &e) {
      logger_str = "Could not find node_info for node name <" + node_name +
                   "> - " + std::string(e.what());
      svk_logger(CONTROLLER_LOGGER_MODULE_NAME, level_E::ERROR,
                 logger_str.c_str());
      return status;
    }
    status = 0;
  }

  return status;
}

Status RunStatsCommand(ControllerServicer *svcr, std::string const &node_name,
                       const std::string &feature_name,
                       const std::string &command_name,
                       const std::string &command_params, json &output_json) {
  std::string t_node_ip;
  std::string t_node_port;
  std::string t_cluster_name;
  std::string output_str;
  std::string logger_str;
  int status = -1;
  Status cmd_status;

  status = svcr->HlprGetNodeDetails(node_name, t_node_port, t_cluster_name,
                                    t_node_ip);
  if (status != 0) {
    logger_str = "Error in getting node details <" + node_name +
                 ">. Internal structure looks corrupted";
    svk_logger(CONTROLLER_LOGGER_MODULE_NAME, level_E::ERROR,
               logger_str.c_str());
    return Status(grpc::INVALID_ARGUMENT, logger_str);
  }

  cmd_status = SendNodeCommand(t_node_ip, t_node_port, feature_name,
                               command_name, command_params, output_str);
  if (cmd_status.ok() != true) {
    logger_str = "Error in getting node stats for <" + node_name + ">.";
    svk_logger(CONTROLLER_LOGGER_MODULE_NAME, level_E::ERROR,
               logger_str.c_str());
    return Status(grpc::UNKNOWN, logger_str);
  }

  try {
    output_json = json::parse(output_str);
  } catch (json::parse_error &e) {
    logger_str = "Error in parsing the output json string for node <" +
                 node_name + ">, output <" + output_str + "> - " +
                 std::string(e.what());
    svk_logger(CONTROLLER_LOGGER_MODULE_NAME, level_E::ERROR,
               logger_str.c_str());
    return Status(grpc::UNKNOWN, logger_str);
  }

  return Status::OK;
}

Status ControllerServicer::StatsAPI(ServerContext *ctxt,
                                    const svk::StatsRequest *req,
                                    svk::StatsResponse *resp) {
  std::string logger_str;
  Status cmd_status;

  std::string cluster_name = req->cluster_name();
  std::string node_name = req->node_name();
  std::string application_name = req->application_name();
  std::string feature_name = req->feature_name();
  std::string command_name = req->command_name();
  std::string command_params = req->command_params();
  json json_response;

  resp->set_api_version(API_VERSION);

  logger_str = "StatsAPI called with feature: " + feature_name +
               " command: " + command_name + " params: " + command_params;
  svk_logger(CONTROLLER_LOGGER_MODULE_NAME, level_E::INFO, logger_str.c_str());

  if (command_name.length() == 0) {
    logger_str = "StatsAPI called with empty command_name";
    svk_logger(CONTROLLER_LOGGER_MODULE_NAME, level_E::ERROR,
               logger_str.c_str());
    cmd_status = Status(grpc::INVALID_ARGUMENT, logger_str);
    return cmd_status;
  }

  if (cluster_name.length()) {
    cluster_info cluster_details;
    try {
      // Note: must use the node_name to find the ip/cluster, not the IP
      cluster_details = m_cluster_info.at(cluster_name);
    } catch (const std::out_of_range &e) {
      logger_str = "Could not find the cluster name <" + cluster_name +
                   ">. - " + std::string(e.what());
      svk_logger(CONTROLLER_LOGGER_MODULE_NAME, level_E::ERROR,
                 logger_str.c_str());
      resp->set_error_id_or_string_if_any(logger_str);
      resp->set_error_code(SVK_STATUS_FAIL);
      return Status(grpc::INVALID_ARGUMENT, logger_str);
    }

    for (const auto &t_node_name : cluster_details.node_names) {
      if (node_name.length() && node_name != t_node_name) {
        continue;
      }
      json node_output_json;
      cmd_status =
          RunStatsCommand(this, t_node_name, feature_name, command_name,
                          command_params, node_output_json);
      if (cmd_status.ok() != true) {
        return cmd_status;
      }
      json_response[t_node_name] = node_output_json;
    }
    resp->set_response(json_response.dump());

  } else if (node_name.length()) {
    json node_output_json;
    cmd_status = RunStatsCommand(this, node_name, feature_name, command_name,
                                 command_params, node_output_json);
    if (cmd_status.ok() != true) {
      return cmd_status;
    }
    json_response[node_name] = node_output_json;
    resp->set_response(json_response.dump());
  } else {
    json node_output_json;
    for (const auto &[key, node] : m_registered_nodes) {
      cmd_status =
          RunStatsCommand(this, node.node_name, feature_name, command_name,
                          command_params, node_output_json);

      if (cmd_status.ok() != true) {
        continue;
      }
      json_response[node.node_name] = node_output_json;
    }
    resp->set_response(json_response.dump());
  }

  return Status(grpc::OK, "Success");
}

std::shared_ptr<Server> InitializeServicer(ControllerServicer *svcr) {
  std::string logger_str;

  if (svcr == nullptr || svcr->get_svk_config_controller_id().length() == 0 ||
      svcr->get_svk_config_controller_port().length() == 0) {
    svk_logger(
        CONTROLLER_LOGGER_MODULE_NAME, level_E::ERROR,
        "Invalid servicer object or the node_id and the port are invalid");
    return nullptr;
  }
  std::string server_address = svcr->get_svk_config_controller_id() + ":" +
                               svcr->get_svk_config_controller_port();

  logger_str = "Server listening on " + server_address;
  svk_logger(CONTROLLER_LOGGER_MODULE_NAME, level_E::INFO, logger_str.c_str());

  grpc::EnableDefaultHealthCheckService(true);
  grpc::reflection::InitProtoReflectionServerBuilderPlugin();
  ServerBuilder builder;
  int selected_port;

  // Listen on the given address without any authentication mechanism.
  builder.AddListeningPort(server_address, grpc::InsecureServerCredentials(),
                           &selected_port);

  // Register "service" as the instance through which we'll communicate with
  // clients. In this case it corresponds to an *synchronous* service.
  // builder.RegisterService(new Servicer(svk_conf_file, framework_lib_path));
  builder.RegisterService(svcr);
  // Finally assemble the server.
  std::shared_ptr<Server> server(builder.BuildAndStart());
  if (server == nullptr) {
    svk_logger(CONTROLLER_LOGGER_MODULE_NAME, level_E::ERROR,
               "Controller Server failed to start");
    return nullptr;
  }

  svcr->set_server(server);

  svk_logger(CONTROLLER_LOGGER_MODULE_NAME, level_E::INFO,
             "Controller Server instance successfully created");
  // Wait for the server to shutdown. Note that some other thread must be
  // responsible for shutting down the server for this call to ever return.
  return server;
}

