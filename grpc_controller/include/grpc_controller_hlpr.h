#ifndef __GRPC_CONTROLLER_HLPR_H__
#define __GRPC_CONTROLLER_HLPR_H__

#include "grpc_controller.h"

/**
 * @brief Data structure to fill the event data details
 * @param category Category of the event - alarm, metric, config, sla,log,
 * health, info, traces
 * @param severity Severity of the event. In case of regular event, the severity
 * is one of the following - info, warning, critical In case of health, the
 * severity is one of degraded, good, failed
 * @param host_name Node name where the event is generated from
 * @param app_name Application name for which the event is generated for
 * @param app_pid Application PID
 * @param event_tag Event Tag generated by the main event
 * @param source_type Source type in one of the cluster, application, node,
 * device, numa_node
 * @param source Actual info of the source_type. In case of application, it is
 * App PID
 * @param message Message to be posted for the event
 * @param cluster_name Name of the cluster the node is part of
 *
 */

struct ControllerEventData {
  std::string category;
  std::string severity;
  std::string host_name;
  std::string app_name;
  std::string app_pid;
  std::string event_tag;
  std::string source_type;
  std::string source;
  std::string message;
  std::string cluster_name;

  // Constructor to initialize the struct members
  ControllerEventData(const std::string& category, const std::string& severity,
                      const std::string& host_name, const std::string& app_name,
                      const std::string& app_pid, const std::string& event_tag,
                      const std::string& source_type, const std::string& source,
                      const std::string& message,
                      const std::string& cluster_name)
      : category(category),
        severity(severity),
        host_name(host_name),
        app_name(app_name),
        app_pid(app_pid),
        event_tag(event_tag),
        source_type(source_type),
        source(source),
        message(message),
        cluster_name(cluster_name) {}
  ControllerEventData() = default;
};

int GenerateControllerEvent(const ControllerEventData& event_data);
std::shared_ptr<Server> InitializeServicer(ControllerServicer* svcr);
int StartServer(const std::string& svk_conf_file, bool blocking);
void signal_handler(int signal);
int StartEventProcessingThread(ControllerServicer* svcr);
int StopEventProcessingThread(ControllerServicer* svcr);
int StopAllThreads(ControllerServicer* svcr);
int StartThreadForZMQSubscriberConfiguration(ControllerServicer* svcr);
void ProcessRASEvent(json json_data, ControllerServicer* svcr);
void ProcessSLAEvent(json json_data, ControllerServicer* svcr);
void systemd_notify(int ready, const char* status);
void ControllerHealthCheckServicer(std::shared_ptr<Server> ctrl_server,
                                   bool enable);

#endif /*__GRPC_CONTROLLER_HLPR_H__*/
