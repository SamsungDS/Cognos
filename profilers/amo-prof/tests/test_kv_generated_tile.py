#!/usr/bin/env python3
"""The "KV cache generated this run" tile, and what it refuses to claim.

Run: python3 tests/test_kv_generated_tile.py

"Generated" means KV the GPUs actually COMPUTED:

    generated = (prompt - cached) + decode

A prefill token served from the prefix cache reuses KV that already exists;
it generates none. On the reference runs the hit rate is ~95%, so counting
all prompt tokens instead overstates the total about twentyfold — which is
the whole reason this tile needs a definition rather than just a counter.

Both terms are measured counters, so this does not inherit the error in
recomputed_tok, which derives the prefill total from the hit-rate gauge.

The byte figure is the part to be careful with. On the reference run the
model config gives 960 KB/token exactly — 2 x 60 layers x 16 kv_heads x 256
head_dim x 2 bytes — and that is arithmetically right and physically
unreconciled: it implies 18,788 GB for the tokens the engine says it backed
up, against 546.9 GB the drive actually recorded. 34x apart. So the tile
reports the measured token count as its own figure and treats the byte
figure as an upper bound, saying so, rather than publishing a GB number that
contradicts the hardware by a factor of thirty.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))

from amoprof.report.metric_kernels import (  # noqa: E402
    resolve_kv_bytes_per_token,
)

# From the v1.61.1 L3-local-vs-L3.5 comparison report.
LOCAL = dict(prompt=101_488_872, cached=97_142_810, decode=115_240,
             backup=20_521_688, ssd_written_gb=546.9, tp=8)
L35 = dict(prompt=233_882_911, cached=223_899_043, decode=330_907,
           backup=15_769_208, ssd_written_gb=0.0, tp=8)
CFG = {"num_hidden_layers": 60, "num_key_value_heads": 16, "head_dim": 256,
       "torch_dtype": "bfloat16"}

_RESULTS = []


def _check(name, got, want):
    ok = got == want
    _RESULTS.append((ok, name))
    print(f"  {'PASS' if ok else 'FAIL'}  {name}")
    if not ok:
        print(f"        got  {got!r}\n        want {want!r}")


def _generated(d):
    return max(0, d["prompt"] - d["cached"]) + d["decode"]


def main() -> int:
    print("\nThe definition excludes cache hits")
    g = _generated(LOCAL)
    _check("local run computed KV for 4,461,302 tokens", g, 4_461_302)
    _check("which is prompt - cached + decode",
           g, LOCAL["prompt"] - LOCAL["cached"] + LOCAL["decode"])
    naive = LOCAL["prompt"] + LOCAL["decode"]
    _check("counting all prompt tokens would overstate it 22.8x",
           round(naive / g, 1), 22.8)
    _check("and the overstatement is 1/(1 - hit rate), as it must be",
           round(naive / g, 0), round(1 / (1 - LOCAL["cached"] / naive), 0))
    _check("L3.5 computed KV for 10,314,775 tokens", _generated(L35),
           10_314_775)

    print("\nThe KV geometry resolves exactly from a model config")
    r = resolve_kv_bytes_per_token(model_name="google/gemma-4-31b-it",
                                   kv_dtype="bfloat16", config=CFG)
    _check("960 KB/token", r["kb"], 960.0)
    _check("marked exact", r["exact"], True)
    _check("and says where it came from", r["source"], "model config (exact)")
    _check("2 x 60 x 16 x 256 x 2 = 983,040 bytes",
           2 * 60 * 16 * 256 * 2, 983_040)
    _check("an fp8 KV cache halves it",
           resolve_kv_bytes_per_token(model_name="google/gemma-4-31b-it",
                                      kv_dtype="fp8_e5m2",
                                      config=CFG)["kb"], 480.0)
    # No config and an unrecognised name must NOT fall through to a default.
    _check("an unresolvable model returns zero, not a default",
           resolve_kv_bytes_per_token(model_name="some-unknown-model-7x",
                                      kv_dtype="fp16", config={})["kb"], 0.0)

    print("\nThe byte figure does not reconcile with the device, and says so")
    kb = r["kb"]
    implied = LOCAL["backup"] * kb / (1024 * 1024)
    _check("960 KB/token implies 18,788 GB for the backed-up tokens",
           round(implied), 18_788)
    _check("the drive recorded 546.9 GB", LOCAL["ssd_written_gb"], 546.9)
    _check("34.4x apart", round(implied / LOCAL["ssd_written_gb"], 1), 34.4)
    _check("still 4.3x apart if the stored KV is per-rank",
           round(implied / LOCAL["tp"] / LOCAL["ssd_written_gb"], 1), 4.3)
    _check("so the tile's >2x threshold fires",
           implied / LOCAL["ssd_written_gb"] > 2.0, True)

    print("\nAnd the engine says it backed up more than it computed")
    _check("backup exceeds generated by 4.6x",
           round(LOCAL["backup"] / g, 1), 4.6)
    _check("which is impossible, so that check fires too",
           LOCAL["backup"] > g * 1.02, True)

    print("\nThe tile's own source carries each of those behaviours")
    src = (pathlib.Path(__file__).resolve().parent.parent / "amoprof"
           / "report" / "combined.py").read_text()
    _check("the tile exists", '"KV cache generated this run"' in src, True)
    _check("it excludes cached tokens from the count",
           "_kvg_recomp = max(0.0, _kvg_prompt - _kvg_cached)" in src, True)
    _check("it adds the decode tokens",
           "_kvg_new_tok = _kvg_recomp + _kvg_decode" in src, True)
    _check("it reports tokens when the geometry is unresolvable",
           "The byte figure needs KV bytes per" in src, True)
    _check("and substitutes no default for it",
           "No default is " in src, True)
    _check("it distinguishes a measured zero from absent counters",
           '"0 tok"' in src, True)
    _check("it states full-model and per-rank",
           "Full-model across all ranks" in src, True)
    _check("it checks backup against generated",
           "KV cannot be persisted before it is computed" in src, True)
    _check("it reconciles against the device",
           "Not reconciled with the device" in src, True)
    _check("re-deriving the measured total rather than reusing write_gb",
           "_kvg_meas_wr = _safe_float(_pick(blk," in src, True)
    # That last one matters: write_gb is reassigned to the ESTIMATE further
    # down, so a check against it would compare the figure with itself.
    _check("and the reason is recorded where the next reader will see it",
           "would compare this figure against itself" in src, True)
    _check("the counterfactual and the saving are both shown",
           "would have computed" in src and "hierarchy avoided" in src, True)

    print("\nThe comparison rows render against real CSVs")
    import json as _json, logging as _lg, re as _re, shutil as _sh
    import tempfile as _tf, html as _H
    _lg.basicConfig(level=_lg.CRITICAL)
    from amoprof.comparator import (
        RunSpec as _RS, extract_metrics as _em,
        build_layer_walk_html as _walk,
    )
    _tmp = pathlib.Path(_tf.mkdtemp(prefix="amoprof_kv_"))
    try:
        def _mk(_n, _d, _cfg=True):
            _raw = _tmp / _n / "raw"
            _raw.mkdir(parents=True)
            # The column names extract_metrics actually reads. An earlier
            # draft of this test used `cached_tokens_total`, which it does
            # not, so cached_tok came back None and the rows silently
            # vanished from the table instead of failing.
            _raw.joinpath("sglang_timeseries.csv").write_text(
                "time_sec,prompt_tokens_total,"
                "realtime_tokens_total[mode=prefill_cache],"
                "generation_tokens_total\n0,0,0,0\n"
                f"2940,{_d['prompt']},{_d['cached']},{_d['decode']}\n")
            _raw.joinpath("setup_details.json").write_text(_json.dumps(
                {"Model": "google/gemma-4-31b-it", "TP size": _d["tp"]}))
            if _cfg:
                _raw.joinpath("model_config.json").write_text(_json.dumps(CFG))
            return _em(_RS(label=_n, raw_dir=_raw))

        _a = _mk("local", LOCAL)
        _b = _mk("l35", L35)
        _c = _mk("no config", LOCAL, _cfg=False)
        _check("cached tokens are read from the right column",
               _a.cached_tok, float(LOCAL["cached"]))
        _check("so the generated count is populated",
               _a.kv_generated_tok, float(_generated(LOCAL)))
        _check("and the byte figure with it",
               round(_a.kv_generated_gb or 0, 1), 4084.4)
        _check("the L3.5 run too", round(_b.kv_generated_gb or 0, 1), 9443.5)

        def _row(_h, _frag):
            for _m in _re.finditer(
                    r"<tr class='chain-row'><td>(.*?)</td>(.*?)</tr>",
                    _h, _re.S):
                _lab = _H.unescape(_re.sub(r"<[^>]+>", "", _m.group(1))).strip()
                if _frag in _lab:
                    return [_H.unescape(_re.sub(r"<[^>]+>", "", _x)).strip()
                            for _x in _re.findall(
                                r"<td class='num'>(.*?)</td>", _m.group(2),
                                _re.S)]
            return None

        _h2 = _walk([_a, _c])
        _check("an exact geometry is named as exact",
               _row(_h2, "where the KV geometry came from")[0], "model config (exact)")
        _check("and a size hint is named as an estimate",
               _row(_h2, "where the KV geometry came from")[1],
               "size hint '31b' (ESTIMATE — assumed layout)")
        _check("without doubling the word",
               _row(_h2, "where the KV geometry came from")[1].count("ESTIMATE"), 1)
        # 256 vs 960 KB/token is a 3.75x error, so bytes require exactness.
        _check("the size hint is 3.75x wrong on this model",
               round(960.0 / (_c.kv_bytes_tok_kb or 1), 2), 3.75)
        _check("so no byte figure is published from it",
               _row(_h2, "KV generated · bytes")[1], "not exported")
        _check("the token count still is, because it is measured",
               _row(_h2, "KV generated · tokens")[1],
               f"{_generated(LOCAL):,}")
        # A counterfactual beside an actual that reads "not exported" would
        # offer a saving against nothing.
        _check("the counterfactual is withheld with it",
               _row(_h2, "no cache at all")[1], "not exported")
        _check("and so is the saving",
               _row(_h2, "avoided by the hierarchy")[1], "not exported")
        _check("while the exact column keeps all three",
               [_row(_h2, k)[0] for k in ("KV generated · bytes",
                                          "no cache at all",
                                          "avoided by the hierarchy")],
               ["4,084.4 GB", "93,021.3 GB", "88,936.9 GB"])
    finally:
        _sh.rmtree(_tmp, ignore_errors=True)

    print("\nThe comparison report carries the same rows")
    cmp_src = (pathlib.Path(__file__).resolve().parent.parent / "amoprof"
               / "comparator.py").read_text()
    for probe, what in (
            ('"KV generated · tokens computed"', "the token row"),
            ('"KV generated · bytes"', "the byte row"),
            ('"↳ KV bytes per token used"', "the KB/token row"),
            ('"↳ with no cache at all · counterfactual"', "the counterfactual"),
            ('"↳ avoided by the hierarchy"', "the saving")):
        _check(f"{what} is present", probe in cmp_src, True)
    _check("it resolves KV bytes through the shared kernel",
           "resolve_kv_bytes_per_token as _rkv" in cmp_src, True)
    _check("so the two surfaces cannot disagree about one model",
           "cannot report different KV bytes per token" in cmp_src
           or "different KV bytes per token for one model" in cmp_src, True)

    print("\nThe tile renders on all four counter states")
    import tempfile as _tf2, shutil as _sh2, html as _H2
    from amoprof.report.combined import (
        build_executive_summary_html as _bexec)

    def _mk_run(_base, *, prompt=True, cached="cached_tokens_total",
                decode=True, hit_gauge=False):
        _raw = _base / "raw"
        _raw.mkdir(parents=True)
        _cols, _r0, _r1 = ["time_sec"], [0.0], [600.0]
        def _add(_n, _a, _b):
            _cols.append(_n); _r0.append(_a); _r1.append(_b)
        if prompt:
            _add("sglang_prompt_tokens_total", 0, 204_050_007)
        if cached:
            _add(f"sglang_{cached}", 0, 201_493_601)
        if decode:
            _add("sglang_generation_tokens_total", 0, 225_018)
        _raw.joinpath("sglang_timeseries.csv").write_text(
            ",".join(_cols) + "\n"
            + ",".join(str(v) for v in _r0) + "\n"
            + ",".join(str(v) for v in _r1) + "\n")
        _raw.joinpath("setup_details.json").write_text(_json.dumps(
            {"Model": "google/gemma-4-31b-it", "TP size": 8}))
        _raw.joinpath("model_config.json").write_text(_json.dumps(CFG))
        return _raw

    def _kvg(_raw):
        _s = _H2.unescape(_bexec(_raw, run_label="k"))
        _m = _re.search(
            r'class="kpi-label">KV cache generated this run</div>\s*'
            r'<div class="kpi-value">(.*?)</div>\s*'
            r'<div class="kpi-note">(.*?)</div>', _s, _re.S)
        if not _m:
            return None
        _c = lambda _x: _re.sub(r"\s+", " ", _H2.unescape(
            _re.sub(r"<[^>]+>", " ", _x))).strip()
        return _c(_m.group(1)), _c(_m.group(2))

    _t2 = pathlib.Path(_tf2.mkdtemp(prefix="amoprof_kvg4_"))
    try:
        _a4 = _kvg(_mk_run(_t2 / "all"))
        _check("with all three counters it reports GB",
               _a4[0], "2,546.5 GB")
        _check("from 2,781,424 computed tokens",
               "2,781,424 tokens of KV actually computed" in _a4[1], True)

        # The engine may export only realtime_tokens_total{mode=prefill_cache}.
        # _tok_num matches on 'cached_tokens_total', which that name does not
        # contain, so cached silently resolved to 0.
        _b4 = _kvg(_mk_run(_t2 / "realtime",
                           cached="realtime_tokens_total[mode=prefill_cache]"))
        _check("a prefill_cache-only engine resolves the same figure",
               _b4[0], _a4[0])
        _check("and is not flagged as unresolved",
               "did not resolve" in _b4[1], False)

        _c4 = _kvg(_mk_run(_t2 / "nocached", cached=None))
        _check("with no cached counter the figure is 73x higher",
               round(187_019.4 / 2_546.5, 0), 73.0)
        _check("which is what it reports", _c4[0], "187,019.4 GB")
        _check("but it says the cached total did not resolve",
               "Cached prompt tokens did not resolve" in _c4[1], True)
        # The factor is NOT 1/(1-h): decode sits in both terms, so the real
        # ratio is (prompt+decode)/(prompt*(1-h)+decode) -- 73.4x here where
        # 1/(1-h) says 79.8x.  Quoting the looser number would misstate the
        # error while reporting it.
        _check("it does not quote the prefill-only 1/(1-hit) form",
               "1/(1−hit rate) too high" in _c4[1], False)
        _check("it says which form it used",
               "not 1/(1 − hit), which ignores decode" in _c4[1]
               or "cannot be stated" in _c4[1], True)
        _check("and the two forms differ on these numbers",
               [round(187_019.4 / 2_546.5, 1),
                round(1 / (1 - 201_493_601 / 204_050_007), 1)],
               [73.4, 79.8])
        # 1/(1-0) = 1x would read as "no error" on a tile two orders of
        # magnitude high, so no factor is stated without a hit rate.
        _check("without inventing a 1x factor when the hit rate is also gone",
               "is 1×" in _c4[1], False)
        _check("saying so instead",
               "cannot be stated" in _c4[1], True)
        _check("and it drops the accent, since the number is not trustworthy",
               'border-color:#6366f1"><div class="kpi-label">KV cache'
               in _H2.unescape(_bexec(_mk_run(_t2 / "noacc", cached=None),
                                      run_label="k")), False)

        # The case that had no branch at all.
        _d4 = _kvg(_mk_run(_t2 / "none", prompt=False, cached=None,
                           decode=False))
        _check("with no counters the tile still renders",
               _d4 is not None, True)
        _check("as not collected", _d4[0], "not collected")
        _check("naming the summary key it tried",
               "cache_hit_token_weighted_denominator_tokens" in _d4[1], True)
        _check("and the timeseries columns",
               "sglang_prompt_tokens_total" in _d4[1]
               and "sglang_generation_tokens_total" in _d4[1], True)
        _check("reporting which of the three resolved",
               _d4[1].count("did not resolve"), 3)
        _check("and pointing at the wrong-host case that returns an empty "
               "series", "not the memory node" in _d4[1], True)
    finally:
        _sh2.rmtree(_t2, ignore_errors=True)

    bad = [n for ok, n in _RESULTS if not ok]
    print(f"\n{len(_RESULTS) - len(bad)}/{len(_RESULTS)} passed"
          + (f" — FAILED: {', '.join(bad)}" if bad else ""))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
